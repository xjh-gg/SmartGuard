# ============================================================
#  SmartGuard TinyML 训练脚本 v1
#  数据: sensor_data.csv + intrusion_data.csv (合并)
#  模型: sklearn MLPClassifier (2层隐藏)
#  输出: ml_inference.h + scaler_params.h (STM32 用)
#
#  运行: python train_sklearn.py
# ============================================================
import numpy as np
import pandas as pd
import os, glob, re
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.metrics import classification_report, confusion_matrix

# ============ 1. 加载数据 ============
data_dir = os.path.dirname(os.path.abspath(__file__))
csv_files = glob.glob(os.path.join(data_dir, "*.csv"))
csv_files = [f for f in csv_files if "backup" not in f.lower() and "combined" not in f.lower() and "example" not in f.lower()]

print(f"发现 {len(csv_files)} 个 CSV 文件:")
for f in csv_files:
    print(f"  - {os.path.basename(f)}")

dfs = []
for f in csv_files:
    df = pd.read_csv(f)
    # 列名可能不同, 统一处理
    cols_rename = {}
    for c in df.columns:
        cl = c.lower().strip()
        if cl in ("light", "light_adc"):     cols_rename[c] = "light"
        elif cl in ("distance_cm", "dist"):  cols_rename[c] = "distance"
        elif cl in ("temp_c", "temp"):       cols_rename[c] = "temp"
        elif cl in ("humi_pct", "humi"):     cols_rename[c] = "humidity"
        elif cl in ("alert", "alert_type"):  cols_rename[c] = "alert"
    df = df.rename(columns=cols_rename)
    dfs.append(df[["light", "distance", "temp", "humidity", "alert"]])

df = pd.concat(dfs, ignore_index=True)
df = df.dropna()

print(f"\n合并后: {len(df)} 行")
print(f"alert 分布: {dict(df['alert'].value_counts().sort_index())}")

# ============ 2. 特征工程 ============
# 10 维特征: 5 原始 + 5 "偏离中位数"
features_raw = ["light", "distance", "temp", "humidity"]
medians = df[features_raw].median()
print(f"\n基线中位数:")
for k, v in medians.items():
    print(f"  {k}: {v:.2f}")

X_raw = df[features_raw].values
X_dev = df[features_raw].values - medians.values  # 偏离量
X = np.hstack([X_raw, X_dev])                     # 8 维

# 再加两个派生特征: 距离的倒数 (近的变化更敏感)
inv_dist = 1.0 / (df["distance"].values + 1.0).reshape(-1, 1)
dist_sq = (df["distance"].values ** 2).reshape(-1, 1)
X = np.hstack([X, inv_dist, dist_sq])             # 10 维

y = df["alert"].values.astype(int)

print(f"\n特征矩阵: {X.shape}")
print(f"  特征 = [light, dist, temp, humi, light_dev, dist_dev, temp_dev, humi_dev, inv_dist, dist_sq]")

# ============ 3. 划分 + 标准化 ============
# 分层划分, 让每个 split 里 alert 比例一致
if len(np.unique(y)) > 1 and min(np.bincount(y)) >= 2:
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=42, stratify=y)
else:
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=0.25, random_state=42)

scaler = StandardScaler()
X_train_s = scaler.fit_transform(X_train)
X_test_s  = scaler.transform(X_test)

print(f"\n训练集: {X_train.shape[0]} 行 (alert=1: {sum(y_train==1)})")
print(f"测试集: {X_test.shape[0]} 行 (alert=1: {sum(y_test==1)})")

# ============ 4. 训练 MLP ============
# 输入 10 → 隐藏 16 → 隐藏 8 → 输出 4 (one-hot)
mlp = MLPClassifier(
    hidden_layer_sizes=(16, 8),
    activation='relu',
    solver='adam',
    max_iter=500,
    random_state=42,
    early_stopping=True,
    validation_fraction=0.15
)
mlp.fit(X_train_s, y_train)

print(f"\n训练完成! 迭代 {mlp.n_iter_} 次")

# ============ 5. 评估 ============
y_pred = mlp.predict(X_test_s)
print("\n=== 分类报告 (测试集) ===")
classes = sorted(np.unique(y))
names = [f"cls_{i}" for i in classes]
print(classification_report(y_test, y_pred, labels=classes, target_names=names, zero_division=0))
print("=== 混淆矩阵 ===")
cm = confusion_matrix(y_test, y_pred)
print(cm)

# 如果只有 0 和 1, 单独算 intrusion 指标
if len(np.unique(y)) == 2 and sum(y_test==1) > 0:
    tp = sum((y_test==1) & (y_pred==1))
    fn = sum((y_test==1) & (y_pred==0))
    fp = sum((y_test==0) & (y_pred==1))
    print(f"\n入侵检测: TP={tp} FN={fn} FP={fp}")
    print(f"  Recall(不能漏报): {tp/(tp+fn)*100:.1f}%" if tp+fn>0 else "  Recall: N/A")
    print(f"  Precision: {tp/(tp+fp)*100:.1f}%" if tp+fp>0 else "  Precision: N/A")

# ============ 6. 导出 C 头文件 ============
out_dir = data_dir
os.makedirs(out_dir, exist_ok=True)

# 6a. scaler 参数
with open(os.path.join(out_dir, "scaler_params.h"), "w", encoding="utf-8") as f:
    f.write("// Auto-generated by train_sklearn.py — DO NOT EDIT\n")
    f.write(f"// 特征均值 (shape={scaler.mean_.shape})\n")
    f.write("static const float SCALER_MEAN[10] = {")
    f.write(", ".join(f"{v:.6f}f" for v in scaler.mean_))
    f.write("};\n\n")
    f.write(f"// 特征标准差 (shape={scaler.scale_.shape})\n")
    f.write("static const float SCALER_SCALE[10] = {")
    f.write(", ".join(f"{v:.6f}f" for v in scaler.scale_))
    f.write("};\n")
print(f"\n已导出 scaler_params.h")

# 6b. MLP 权重 (逐层)
W1, b1 = mlp.coefs_[0], mlp.intercepts_[0]   # 10→16
W2, b2 = mlp.coefs_[1], mlp.intercepts_[1]   # 16→8
W3, b3 = mlp.coefs_[2], mlp.intercepts_[2]   # 8→n_classes
n_out = W3.shape[1]

def write_mat(f, name, arr):
    r, c = arr.shape
    f.write(f"// {name}: {r}x{c}\n")
    f.write(f"static const float {name}[{r}][{c}] = {{\n")
    for i in range(r):
        row = ", ".join(f"{v:.8f}f" for v in arr[i])
        f.write(f"    {{{row}}},\n")
    f.write("};\n\n")

with open(os.path.join(out_dir, "ml_inference.h"), "w", encoding="utf-8") as f:
    f.write("// Auto-generated by train_sklearn.py — DO NOT EDIT\n")
    f.write("// 模型: MLP(10→16→8→4), relu, adam\n")
    f.write("// 部署后用 ml_predict() 做端侧推理\n\n")
    f.write("#ifndef ML_INFERENCE_H\n#define ML_INFERENCE_H\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write("#define ML_INPUT_DIM   10\n")
    f.write("#define ML_HIDDEN1     16\n")
    f.write("#define ML_HIDDEN2     8\n")
    f.write(f"#define ML_OUTPUT_DIM  {n_out}\n\n")

    write_mat(f, "ML_W1", W1)
    f.write(f"static const float ML_B1[{len(b1)}] = {{")
    f.write(", ".join(f"{v:.8f}f" for v in b1))
    f.write("};\n\n")

    write_mat(f, "ML_W2", W2)
    f.write(f"static const float ML_B2[{len(b2)}] = {{")
    f.write(", ".join(f"{v:.8f}f" for v in b2))
    f.write("};\n\n")

    write_mat(f, "ML_W3", W3)
    f.write(f"static const float ML_B3[{len(b3)}] = {{")
    f.write(", ".join(f"{v:.8f}f" for v in b3))
    f.write("};\n\n")

    f.write("""
// ReLU
static inline float relu(float x) { return x > 0 ? x : 0; }

// argmax
static inline uint8_t argmax(float *arr, uint8_t n) {
    uint8_t best = 0; float bv = arr[0];
    for (uint8_t i = 1; i < n; i++)
        if (arr[i] > bv) { bv = arr[i]; best = i; }
    return best;
}

/**
 * @brief  端侧 TinyML 推理 — 10维输入 → 分类标签 (0-3)
 * @param  x_raw[4]  原始传感器值: [light, distance, temp, humidity]
 * @param  baseline[4] 自适应阈值的基线值 (同顺序)
 * @param  scaler_mean[10], scaler_scale[10]  来自 scaler_params.h
 * @return 预测类别: 0=OK 1=INTRUSION 2=FIRE 3=ENV_ABNORMAL
 *
 *  总计算量: ~3800 次 FMA, 约 40KB Flash (3层权重)
 *  STM32F407 @168MHz: < 1ms 推理
 */
static uint8_t ml_predict(float *x_raw, float *baseline,
                          const float *scaler_mean, const float *scaler_scale) {
    float x[10], h1[16], h2[8], out[ML_OUTPUT_DIM];
    uint8_t i, j;

    // ---- 1. 特征工程 ----
    x[0] = x_raw[0];                 // light
    x[1] = x_raw[1];                 // distance
    x[2] = x_raw[2];                 // temp
    x[3] = x_raw[3];                 // humidity
    x[4] = x_raw[0] - baseline[0];   // light_dev
    x[5] = x_raw[1] - baseline[1];   // dist_dev
    x[6] = x_raw[2] - baseline[2];   // temp_dev
    x[7] = x_raw[3] - baseline[3];   // humi_dev
    x[8] = 1.0f / (x_raw[1] + 1.0f); // inv_dist
    x[9] = x_raw[1] * x_raw[1];      // dist_sq

    // ---- 2. 标准化 ----
    for (i = 0; i < 10; i++)
        x[i] = (x[i] - scaler_mean[i]) / scaler_scale[i];

    // ---- 3. 隐藏层 1: 10→16, ReLU ----
    for (i = 0; i < ML_HIDDEN1; i++) {
        h1[i] = ML_B1[i];
        for (j = 0; j < ML_INPUT_DIM; j++)
            h1[i] += ML_W1[j][i] * x[j];
        h1[i] = relu(h1[i]);
    }

    // ---- 4. 隐藏层 2: 16→8, ReLU ----
    for (i = 0; i < ML_HIDDEN2; i++) {
        h2[i] = ML_B2[i];
        for (j = 0; j < ML_HIDDEN1; j++)
            h2[i] += ML_W2[j][i] * h1[j];
        h2[i] = relu(h2[i]);
    }

    // ---- 5. 输出层: 8→n_out, Softmax 不需要 (argmax 直接比) ----
    for (i = 0; i < ML_OUTPUT_DIM; i++) {
        out[i] = ML_B3[i];
        for (j = 0; j < ML_HIDDEN2; j++)
            out[i] += ML_W3[j][i] * h2[j];
    }

    /* 单输出神经元 (sigmoid/logit), 阈值 0 */ return out[0] > 0.0f ? 1 : 0;
}

#endif /* ML_INFERENCE_H */
""")
print(f"已导出 ml_inference.h")

# ============ 7. 模型摘要 ============
print(f"\n{'='*50}")
print(f"📊  模型摘要")
print(f"{'='*50}")
print(f"  网络结构:  {10}→{mlp.hidden_layer_sizes[0]}→{mlp.hidden_layer_sizes[1]}→{n_out}")
print(f"  激活函数:  ReLU / Softmax(隐式)")
print(f"  训练样本:  {len(X_train)}")
print(f"  测试样本:  {len(X_test)}")
params = sum(W.shape[0]*W.shape[1] for W in mlp.coefs_) + sum(len(b) for b in mlp.intercepts_)
print(f"  总参数:    {params}")
print(f"  Flash 占用: ~{params*4/1024:.1f} KB (float32)")
print(f"  推理耗时:  <1ms @ 168MHz")
print(f"\n✅ 部署文件已生成:")
print(f"   {os.path.join(out_dir, 'scaler_params.h')}")
print(f"   {os.path.join(out_dir, 'ml_inference.h')}")



