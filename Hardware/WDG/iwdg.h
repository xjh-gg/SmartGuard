/**
  ******************************************************************************
  * @file    iwdg.h
  * @brief   STM32F407ZE 独立看门狗（IWDG）驱动头文件
  *
  * 特性：
  *   - 基于 LSI（32KHz）独立时钟，主时钟挂了也能复位 MCU
  *   - 超时 2s（PR=256, RLR=249），task_fast 每轮调度都会喂狗
  *   - 长阻塞操作（基线学习、ESP8266 复位、FLASH 擦除）必须分段喂狗，
  *     否则热复位后 IWDG 已运行，会咬出开机死循环
  ******************************************************************************
  */
#ifndef __IWDG_H
#define __IWDG_H

#include "stm32f4xx.h"

void IWDG_Init(void);   /* 初始化独立看门狗（2s 超时） */
void IWDG_Feed(void);   /* 喂狗（2s 内至少一次） */

#endif /* __IWDG_H */
